describe(`Test verifiers generated by the C++ core`, function () {
  cppVectors.forEach((vector) => {
    it(vector.name, () => {
      const verifier = computeVerifier(
        params.azerothcore,
        Buffer.from(vector.salt, `hex`),
        vector.username,
        vector.password
      );
      expect(verifier.length).to.equal(32);
      expect(verifier.toString(`hex`).toUpperCase()).to.equal(vector.verifier);
    });
  });
});

